function downloadResult() {
    const resultCard = document.getElementById('result-box');

    html2canvas(resultCard, {
        scale: 3, 
        backgroundColor: "#0f0f1b", 
        useCORS: true,
        logging: false, 
        onclone: function(clonedDoc) {
            const clonedBox = clonedDoc.getElementById('result-box');
            
            clonedBox.style.padding = "30px 20px";
            clonedBox.style.background = "linear-gradient(135deg, #16213e 0%, #0f0f1b 100%)";
            clonedBox.style.border = "3px solid #ff9f43";
            clonedBox.style.borderRadius = "20px";

            const cards = clonedBox.querySelectorAll('.card');
            cards.forEach(card => {
                card.style.animation = "none"; 
                card.style.opacity = "1";      
                card.style.background = "#1e2a4a"; 
                card.style.boxShadow = "0 4px 15px rgba(0,0,0,0.5)"; 
            });

            const allTextElements = clonedBox.querySelectorAll('.content, .hint-box');
            allTextElements.forEach(el => {
                el.style.setProperty('color', '#ffffff', 'important');
                el.style.setProperty('opacity', '1', 'important');
                el.style.fontWeight = "bold";
                el.style.textShadow = "1px 1px 2px #000000"; 
            });

            const labels = clonedBox.querySelectorAll('.label');
            labels.forEach(label => {
                label.style.setProperty('color', '#ff9f43', 'important');
                label.style.setProperty('opacity', '1', 'important');
                label.style.fontWeight = "800";
            });

            const hintBoxes = clonedBox.querySelectorAll('.hint-box');
            hintBoxes.forEach(hint => {
                hint.style.background = "#2a3655"; 
                hint.style.border = "1px dashed #ff9f43";
            });

            const watermark = clonedDoc.createElement('div');
            watermark.innerHTML = "✨ Згенеровано у додатку <b>«Альтер-Его»</b> ✨";
            watermark.style.textAlign = "center";
            watermark.style.marginTop = "25px";
            watermark.style.color = "#a4b0be";
            watermark.style.fontSize = "1.1rem";
            watermark.style.fontFamily = "sans-serif";
            watermark.style.opacity = "1";
            clonedBox.appendChild(watermark);
        }
    }).then(canvas => {
        const link = document.createElement('a');
        link.download = 'Moe_Alter_Ego.png';
        link.href = canvas.toDataURL('image/png', 1.0);
        link.click();
    }).catch(err => {
        console.error("Помилка при збереженні:", err);
    });
}

