// Функція перемикання режимів (БРОНЕБІЙНІ КОЛЬОРИ)
function switchMode(mode) {
    currentMode = mode;
    
    // 1. Перемикаємо активну кнопку
    document.querySelectorAll('.mode-btn').forEach(btn => {
        btn.classList.remove('active');
        if(btn.dataset.mode === mode) btn.classList.add('active');
    });

    // 2. Очищаємо всі теми
    document.body.className = '';
    
    // Якщо Опора — додаємо клас для світіння кнопок та рамочок
    if (mode === 'women') {
        document.body.classList.add('theme-women');
    }

    // 3. Словник фонових кольорів для ВСІХ режимів
    const backgrounds = {
        common: '#0f0f1b', // Класика
        politics: 'linear-gradient(135deg, #1a2a3a 0%, #0f0f1b 100%)', // Політика
        history: 'linear-gradient(135deg, #4a2511 0%, #0f0f1b 100%)', // Історія
        profi: 'linear-gradient(135deg, #0a3d62 0%, #0f0f1b 100%)', // Профі
        school: 'linear-gradient(135deg, #1e3c28 0%, #0f0f1b 100%)', // Школа
        meme: 'linear-gradient(135deg, #27ae60 0%, #0f0f1b 100%)', // Меми
        potter: 'linear-gradient(135deg, #3b0918 0%, #0f0f1b 100%)', // Поттер
        fantasy: 'linear-gradient(135deg, #3b0918 0%, #0f0f1b 100%)', // Фентезі (на випадок, якщо ви перейменували)
        gamer: 'linear-gradient(135deg, #4b1b6b 0%, #0f0f1b 100%)', // Геймер
        folk: 'linear-gradient(135deg, #8b0000 0%, #0f0f1b 100%)', // Етно
        kids: 'linear-gradient(135deg, #d35400 0%, #0f0f1b 100%)', // Зоо
        women: 'linear-gradient(135deg, #2a1b2d 0%, #161224 100%)' // Опора (Тепер колір застосовується жорстко)
    };

    // Застосовуємо фон напряму, це переб'є будь-які збої!
    document.body.style.background = backgrounds[mode] || '#0f0f1b';
}

// Функція генерації
function generate() {
    const modeData = db[currentMode];
    
    // 1. ЛОКАЦІЯ
    const cardLoc = document.getElementById('cardLoc');
    const txtLoc = document.getElementById('txtLoc');
    if (document.getElementById('check-loc').checked && modeData.locs) {
        txtLoc.innerText = modeData.locs[Math.floor(Math.random() * modeData.locs.length)];
        cardLoc.style.display = 'block';
    } else {
        cardLoc.style.display = 'none';
    }

    // 2. СИТУАЦІЯ
    const cardSit = document.getElementById('cardSit');
    const txtSit = document.getElementById('txtSit');
    const customSit = document.getElementById('custom-sit-input').value.trim();

    if (customSit !== "") {
        txtSit.innerText = "Моя думка/ситуація: " + customSit;
        cardSit.style.display = 'block';
    } else if (document.getElementById('check-sit').checked && modeData.sits) {
        txtSit.innerText = modeData.sits[Math.floor(Math.random() * modeData.sits.length)];
        cardSit.style.display = 'block';
    } else {
        cardSit.style.display = 'none';
    }

    // 3. ТРАБЛ
    const cardTrb = document.getElementById('cardTrb');
    const txtTrb = document.getElementById('txtTrb');
    if (document.getElementById('check-trb').checked && modeData.trbs) {
        txtTrb.innerText = modeData.trbs[Math.floor(Math.random() * modeData.trbs.length)];
        cardTrb.style.display = 'block';
    } else {
        cardTrb.style.display = 'none';
    }

    // 4. РОЛЬ
    const cardRol = document.getElementById('cardRol');
    const txtRol = document.getElementById('txtRol');
    const randRol = modeData.rols[Math.floor(Math.random() * modeData.rols.length)];
    txtRol.innerText = randRol;
    cardRol.style.display = 'block';

    // Підказка
    const hintBox = document.getElementById('hintBox');
    if (modeData.hints && modeData.hints[randRol]) {
        hintBox.innerText = `💡 "${modeData.hints[randRol]}"`;
        hintBox.style.display = 'block';
    } else {
        hintBox.style.display = 'none';
    }

    // Показуємо кнопку збереження
    document.getElementById('download-btn').style.display = 'inline-block';

    // === МАГІЯ ТАЙМЕРА (Зміна кнопок) ===
    document.getElementById('btnGen').style.display = 'none'; // Ховаємо генерацію
    document.getElementById('btnStart').style.display = 'inline-block'; // Показуємо "Погнали"
    
    document.getElementById('timerLabel').innerText = "Час на підготовку";
    document.getElementById('timerDisplay').innerText = "60"; 
}

// Функція інструкції (Спойлер)
function toggleInstruction() {
    const content = document.getElementById('instruction-content');
    const btn = document.getElementById('toggle-instruction-btn');
    if (content.style.display === "block") {
        content.style.display = "none";
        btn.innerHTML = "❓ Як це працює? (Інструкція)";
    } else {
        content.style.display = "block";
        btn.innerHTML = "❌ Сховати інструкцію";
    }
}

