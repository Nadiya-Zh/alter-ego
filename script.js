let timeLeft = 60; // Скільки секунд даємо на раунд

function startRound() {
    document.getElementById('btnStart').style.display = 'none';
    document.getElementById('timerLabel').innerText = "⏳ Час пішов:";
    timeLeft = 60; 
    document.getElementById('timerDisplay').innerText = timeLeft;

    if (timerInterval) {
        clearInterval(timerInterval);
    }

    timerInterval = setInterval(() => {
        timeLeft--;
        document.getElementById('timerDisplay').innerText = timeLeft;

        if (timeLeft <= 0) {
            clearInterval(timerInterval); 
            document.getElementById('timerLabel').innerText = "⏰ Час вичерпано!";
            document.getElementById('timerDisplay').innerText = "00";
            
            // Повертаємо кнопку генерації
            const btnGen = document.getElementById('btnGen');
            btnGen.style.display = 'block';
            btnGen.innerText = "🔄 ГЕНЕРУВАТИ ЗНОВУ";
        }
    }, 1000); 
}